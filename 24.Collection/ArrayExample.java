// WAP to demostrating Array

public class ArrayExample {
    public static void main(String[] args) {
        // Declaring an array of size 3
        int[] arr = new int[3];

        // Adding elements
        arr[0] = 10;
        arr[1] = 20;
        arr[2] = 30;

        // Accessing elements
        System.out.println(arr[1]);
    }
}
